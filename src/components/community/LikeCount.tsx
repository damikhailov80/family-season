import { HeartDoodle } from '../doodles'
import styles from './LikeCount.module.css'

/**
 * Своя толщина обводки: общая 2.3 на сетке в 64 единицы даёт в рисунке размером
 * с букву 0,65 экранного пикселя — серую паутину. Причина та же, что у слота
 * `spark`, — см. `Icon`.
 */
const HEART_STROKE = 4

/**
 * Сердце со счётом лайков.
 *
 * Мест, где счёт показывают, три: кнопка лайка и надпись на своей публикации в
 * панели выложенного сезона да карточка витрины. Везде это одно и то же —
 * рисунок, отступ, число, — и держать отступ в трёх CSS-модулях значило бы три
 * раза его разойтись. В списке кабинета сердца нет намеренно: там счёт стоит в
 * ряду с «в избранном» и «форками», и рисунок посреди слов только сбивал бы
 * строку.
 *
 * Размер и цвет, наоборот, приходят снаружи: на карточке витрины счёт — часть
 * подписи, а на кнопке он наследует её цвет и белеет вместе с сердцем, когда
 * лайк поставлен.
 *
 * Имя для читалки даёт сам компонент: сердце ей ничего не говорит, а голое
 * число рядом с датой читалось бы как продолжение подписи.
 */
export function LikeCount({
  likes,
  size = 18,
  filled = true,
  /** Ноль скрывается только на кнопке лайка: пустой счёт у свежего сезона
      выглядел бы упрёком автору. В своих же числах автора ноль — данные. */
  hideZero = false,
  label,
  className,
}: {
  likes: number
  size?: number
  filled?: boolean
  hideZero?: boolean
  label?: string
  className?: string
}) {
  return (
    <span
      className={className ? `${styles.likes} ${className}` : styles.likes}
      role="img"
      aria-label={label ?? `Лайков: ${likes}`}
    >
      <HeartDoodle size={size} filled={filled} strokeWidth={HEART_STROKE} />
      {(likes > 0 || !hideZero) && likes}
    </span>
  )
}
