import { notFound } from 'next/navigation'

/**
 * Всё, что не совпало ни с одним адресом внутри языка, — 404 **нашей** страницей
 * (`app/[lang]/not-found.tsx`), а не голой заглушкой Next.
 *
 * Маршрут нужен ровно потому, что корневой лейаут лежит под `[lang]`: обычный
 * `app/not-found.tsx` рисуется в корневом лейауте, а корневого лейаута вне
 * `[lang]` у нас нет — и несовпавший адрес отдавал бы страницу без шапки,
 * подвала и языка. Перехватить он ничего не может: у catch-all самый низкий
 * приоритет, любой настоящий маршрут разбирается раньше.
 */
export default function CatchAll() {
  notFound()
}
