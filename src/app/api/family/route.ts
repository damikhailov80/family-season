import { readFamily } from '../../../server/settings'

/**
 * Состав семьи для **живого** постера. Лист клиентский (`ssr: false`) и до базы
 * не дотягивается, поэтому спрашивает её отсюда.
 *
 * Не путать с составом для **нового** постера: тот уезжает ссылкой из шапки
 * (`SiteHeader`), потому что там бланк собирается заранее. Здесь бланк уже
 * открыт, и подменить в нём людей может только сам лист.
 *
 * Своей обработки ошибок нет намеренно: `readFamily` отдаёт `null` во всех
 * случаях, когда подставлять нечего, — не вошёл, сессия без ключа, настройки
 * нет, база молчит. `null` и означает «кнопки не будет».
 */
export async function GET() {
  return Response.json({ family: await readFamily() })
}
