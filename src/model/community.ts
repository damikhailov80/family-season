import { LIBRARY_LIMIT, type LibraryStatus } from './library'

/**
 * Витрина «Идеи сообщества»: публикация своего сезона, лайки и жалобы.
 *
 * Файл, как и `model/library.ts`, намеренно без серверных зависимостей: его
 * читает и клиентский тулбар, и серверные действия, и сама витрина.
 *
 * Своего предела «сто на аккаунт» здесь нет — он тот же `LIBRARY_LIMIT`, что у
 * сезонов и избранного. Второе такое же число завелось бы только затем, чтобы
 * однажды разойтись с первым.
 */

/** С шестой жалобой сезон пропадает с витрины. Считаются авторы, не нажатия. */
export const REPORTS_TO_HIDE = 5

/** Сколько сезонов показывать за один заход. */
export const IDEAS_PAGE = 10

/**
 * Предел комментария к жалобе. Не бюджет бумаги, как у полей постера, а мера
 * жанра: жалоба — это строчка «здесь мат», а не письмо.
 */
export const COMMENT_LIMIT = 300

/**
 * Чем кончилось действие над витриной. К бедам библиотеки добавлена ровно одна
 * своя: `own` — «это ваш собственный сезон». Она разведена с `error` по той же
 * причине, что и `limit`: человеку понятно, что случилось, и чинить нечего.
 */
export type CommunityStatus = LibraryStatus | 'own'

/**
 * Комментарий к жалобе приходит из браузера. Однострочный и обрезанный — как всё
 * остальное, что мы принимаем снаружи. Пустой возвращается как `null`: жалоба без
 * слов бесполезна тому, кто будет в ней разбираться, и отправлять её незачем.
 */
export function normalizeComment(input: unknown): string | null {
  if (typeof input !== 'string') return null
  return input.replace(/\s+/g, ' ').trim().slice(0, COMMENT_LIMIT) || null
}

/**
 * Слова, которыми витрина объясняет отказ. Живут в модели, а не рядом с
 * кнопками: жаловаться можно и с постера, и с самой витрины, а вторая копия
 * этих строк разошлась бы с первой при первой же правке.
 *
 * `anonymous` сюда не попадает: «войдите» — не отказ, а предложение, и его
 * показывает окно входа. У библиотеки набор слов свой: «не удалось сохранить»
 * про лайк — неправда.
 */
export const COMMUNITY_TEXT: Record<Exclude<CommunityStatus, 'ok' | 'anonymous'>, string> = {
  own: 'Это ваш собственный сезон — лайк и жалоба тут ни к чему.',
  limit: `Больше ${LIBRARY_LIMIT} таких записей на аккаунт мы не храним — уберите лишние.`,
  stale: 'Вход выполнен слишком давно. Обновите страницу и войдите заново.',
  error: 'Не получилось — ошибка на сервере. Попробуйте ещё раз.',
}
