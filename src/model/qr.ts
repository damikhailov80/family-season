import type { Lang } from './lang'
import { QR_PATH, QR_SIZE, QR_URL } from './qr.data'
import { SITE_URL, sharedHref } from './site'

/**
 * Что рисовать в квадрате кода: сторона `viewBox`, путь тёмных модулей и сам
 * адрес — он же подпись для читалки.
 *
 * Кодов на листе бывает два, и различаются они только адресом. По умолчанию
 * стоит адрес сайта: постер висит на холодильнике, и по коду приходят собирать
 * свой сезон. Но у своего сезона может быть выдана личная ссылка — и тогда в
 * коде стоит она: распечатку показывают тем же людям, кому её и отправляют, а
 * с бумаги ссылку иначе не набрать (шестнадцать знаков токена руками не
 * перепечатывают).
 */
export interface QrMatrix {
  size: number
  path: string
  url: string
}

/**
 * Код сайта — тот, что стоит на листе, пока личной ссылки нет. Адрес постоянный,
 * поэтому и матрица собрана заранее (`npm run qr`): считать её на каждый лист
 * незачем.
 */
export const SITE_QR: QrMatrix = { size: QR_SIZE, path: QR_PATH, url: QR_URL }

/**
 * Выданная личная ссылка: токен — окну, где ссылку копируют, готовый код — листу.
 * Ходят они всегда вместе: код собран ровно из этого токена.
 */
export interface SharedLink {
  token: string
  qr: QrMatrix
}

/**
 * Адрес личной ссылки для кода — **абсолютный и от имени сайта**, а не от того
 * хоста, откуда лист открыли: код читают с бумаги, где никакого «текущего
 * адреса» нет.
 *
 * Язык берётся у сезона, а не у интерфейса: им подписан сам лист, и пришедший
 * по коду должен увидеть постер тем же языком, каким он напечатан.
 */
export function shareQrUrl(lang: Lang, token: string): string {
  return `${SITE_URL.replace(/\/+$/, '')}${sharedHref(lang, token)}`
}
