/**
 * Три языка сайта: русский, английский, польский.
 *
 * Файл намеренно без зависимостей — ни серверных, ни клиентских: его читают и
 * `src/proxy.ts` (в среде Edge), и словарь, и модель, и скрипты посева.
 *
 * Язык живёт в двух разных смыслах, и путать их нельзя:
 *   - **язык интерфейса** — им подписаны шапка, кнопки и окна; он стоит в
 *     адресе и хранится кукой (у вошедшего ещё и в базе);
 *   - **язык сезона** — им подписан сам лист (месяц, подписи секций, подсказки
 *     пустых полей); он лежит колонкой рядом с содержимым и не ходит за
 *     настройкой. Чужой выложенный сезон открывают из любого языка.
 */

export const LANGS = ['ru', 'en', 'pl'] as const

export type Lang = (typeof LANGS)[number]

/** Русский — язык, с которого сайт начинался; им же отвечаем, когда не угадали. */
export const DEFAULT_LANG: Lang = 'ru'

/**
 * Подпись языка — на нём самом. Переключатель читает тот, кто нужного языка
 * ещё не видит, и «польский» ему не поможет, а `Polski` — поможет. Поэтому
 * подписи и не едут в словарь: они одинаковы во всех трёх.
 */
export const LANG_LABELS: Record<Lang, string> = {
  ru: 'Русский',
  en: 'English',
  pl: 'Polski',
}

/**
 * Язык из адреса или куки мог написать кто угодно: неизвестный — как будто его
 * нет. `null` вместо подмены нужен `proxy`: «языка в пути нет» и «в пути стоит
 * русский» — разные случаи, во втором редиректа быть не должно.
 */
export function langOrNull(value: unknown): Lang | null {
  return LANGS.includes(value as Lang) ? (value as Lang) : null
}

/** То же, но там, где язык есть всегда: сегмент адреса, колонка в базе. */
export function knownLang(value: unknown): Lang {
  return langOrNull(value) ?? DEFAULT_LANG
}

/**
 * Язык из `Accept-Language`. Разбираем руками: три языка и десяток строк —
 * ради этого тащить `negotiator` с `intl-localematcher` в прокси незачем.
 *
 * `q` учитываем, регион отбрасываем (`pl-PL` → `pl`), незнакомые языки
 * пропускаем: у человека в списке может стоять пять языков, и подходящим
 * окажется третий. Не нашли ни одного — `null`, решает вызывающий.
 */
export function langFromAccept(header: string | null | undefined): Lang | null {
  if (!header) return null

  const wanted = header
    .split(',')
    .map((part) => {
      const [tag, ...params] = part.trim().split(';')
      const q = params.map((p) => p.trim()).find((p) => p.startsWith('q='))
      const weight = q ? Number.parseFloat(q.slice(2)) : 1
      return {
        tag: tag.trim().toLowerCase().split('-')[0],
        weight: Number.isFinite(weight) ? weight : 0,
      }
    })
    // Сортировка обязана быть устойчивой: при равных весах побеждает тот, кто
    // стоит раньше в заголовке. `Array#sort` в ES2019 устойчив, поэтому хватает
    // сравнения весов.
    .sort((a, b) => b.weight - a.weight)

  for (const { tag, weight } of wanted) {
    if (weight <= 0) continue
    const lang = langOrNull(tag)
    if (lang) return lang
  }
  return null
}

/** Имя куки, в которой браузер помнит выбранный язык. */
export const LANG_COOKIE = 'fs-lang'

/** Год: язык выбирают один раз, и переспрашивать его каждый месяц незачем. */
export const LANG_COOKIE_MAX_AGE = 60 * 60 * 24 * 365

/**
 * Откуда взялся язык текущего запроса. Ставит `proxy` заголовком, читает
 * корневой лейаут: язык, стоявший в запрошенном адресе (`url`), сильнее
 * настройки из базы, а подставленный самим `proxy` (`auto`) — слабее.
 *
 * Различить их по одному только адресу нельзя: после редиректа `proxy` язык
 * стоит в пути ровно так же, как если бы его набрали руками. Поэтому `proxy`
 * помечает **свой** редирект куклой-однодневкой `fs-lang-auto` и снимает её на
 * следующем же запросе — см. `src/proxy.ts`.
 */
export type LangSource = 'url' | 'auto'

export const LANG_SOURCE_HEADER = 'x-lang-source'

/**
 * Пометка «язык в адрес подставил я сам».
 *
 * Живёт ровно один переход: `proxy` ставит её на своём редиректе и удаляет,
 * прочитав на следующем запросе. Без неё настройка языка из базы не могла бы
 * победить никогда — заход на голый `/` приходил бы в лейаут неотличимым от
 * адреса, набранного руками.
 */
export const LANG_AUTO_COOKIE = 'fs-lang-auto'

/**
 * Путь без языка, вместе с query (`/seasons?tab=published`, `/s/abc123?p=greece`)
 * — его ставит `proxy` в тот же запрос.
 *
 * Нужен корневому лейауту: чтобы увести человека на тот же адрес в другом языке,
 * надо знать, где он сейчас, а серверному компоненту путь ниоткуда не виден —
 * `headers()` отдаёт только то, что пришло с запросом. Query здесь обязателен:
 * в нём живёт примеренное оформление, и редирект, теряющий его, портит именно
 * ту ссылку, ради которой примерка и заведена.
 */
export const LANG_PATH_HEADER = 'x-lang-path'
