/**
 * Бюджет бумаги: лист печатается ровно в две страницы, и запас расписан до
 * пикселя (см. «Печать» в CLAUDE.md). Лишняя строка в карточке человека
 * умножается на пять и выносит лист на третью страницу.
 *
 * Числа не выведены из кегля, а измерены: постер открывался при печатной ширине
 * 718 px с `media=print`, и для каждого поля считалось, сколько символов реально
 * ложится в строку. Самые тесные пределы определил худший перенос — слова по семь
 * букв подряд. Меняете предел или вёрстку поля — перемеряйте.
 *
 * Числа в скобках ниже — самый длинный текст в готовых примерах: он обязан
 * помещаться, иначе пример поедет по вёрстке при первом же открытии.
 */
export const FIELD_LIMITS: Record<string, number> = {
  /** Заголовок в 46 px между лучами — строка по замыслу одна. (14) */
  'header.title': 20,
  /** Лента с `clip-path`: на двух строках она выглядит порванной. (43) */
  'header.ribbon': 64,
  /** Строка под названием месяца, тоже одна: ниже сразу рамка итогов. (20) */
  'theme.subtitle': 26,
  /** Вопрос итогов стоит внутри растущей рамки — место он берёт у неё, не у страницы. (37) */
  'theme.question': 90,
  /** Подпись лежит поверх рамки: вторая строка наехала бы на содержимое бокса. (33) */
  weeksNote: 48,
  /** Строка между плашкой и ракетой. (27) */
  projectsNote: 48,
  /** Колонка карточки — 159 px, две строки заголовка. (8) */
  'weeks.*.title': 18,
  /** Та же колонка: четыре строки в спокойном тексте, шесть в худшем. (43) */
  'weeks.*.text': 48,
  /** ~432 px рядом с QR: две-три строки. (87 — предел подпёрт примером вплотную) */
  goal: 88,
  /** Колонка под аватаром — 70 px. (6) */
  'people.*.name': 12,
  /** ~278 px рядом с подписью «Проект:». (18) */
  'people.*.project': 22,
  /**
   * ~334 px. Две строки спокойного текста и три — в худшем переносе; 72 символа уже
   * дают четвёртую строку сразу в пяти карточках и третью страницу. (43)
   */
  'people.*.description': 68,
  /**
   * ~517 px рядом с подписью «Моя цель месяца:». Длиннее — и текст сваливается под
   * подпись отдельной строкой, а это +17 px в каждой из пяти карточек. (42)
   */
  'people.*.goal': 52,
}

/** Сеть, а не умолчание: новое поле обязано получить свой измеренный предел. */
const DEFAULT_LIMIT = 48

/** `weeks.2.title` -> `weeks.*.title`: индекс недели и человека предела не меняет. */
export function limitFor(path: string): number {
  return FIELD_LIMITS[path.replace(/\.\d+\./g, '.*.')] ?? DEFAULT_LIMIT
}
