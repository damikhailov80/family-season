import { cookies } from 'next/headers'
import { readConsentSetting } from './settings'
import { CONSENT_COOKIE, consentFromCookie, type Consent } from '../model/consent'

/**
 * Что человек ответил про аналитику — или `null`, если его ещё не спрашивали.
 *
 * Хранилищ два, и старшинство между ними ровно одно: **кука сильнее настройки**.
 * Решение принимают в браузере, и невошедшему больше негде его держать; настройка
 * аккаунта нужна затем, чтобы вошедший не отвечал на один и тот же вопрос на
 * каждом своём устройстве.
 *
 * Хитростей языка (`url` против `auto`, пометка на один переход) здесь нет и не
 * надо: у языка спорят два разных источника догадки, а тут спорят два ответа
 * одного и того же человека, и свежим считается тот, что дан в этом браузере.
 *
 * Настройку читаем **не переписывая куку**. Соблазн завести клиентского близнеца
 * `LangSync` велик, но платить нечем: `readSettings` кэширован `cache()` из
 * React и всё равно вызывается лейаутом ради языка, так что чтение бесплатно, а
 * записывать нечего — куку поставит первое же решение.
 *
 * Молчание базы означает «не знаем», то есть `null`, то есть баннер выйдет ещё
 * раз. Это единственный безопасный ответ: показать лишний раз вопрос неприятно,
 * а молча счесть молчание согласием — нельзя.
 */
export async function readConsent(): Promise<Consent | null> {
  const jar = await cookies()
  const fromCookie = consentFromCookie(jar.get(CONSENT_COOKIE)?.value)
  if (fromCookie) return fromCookie

  return readConsentSetting()
}

/**
 * Идентификатор счётчика — единственное место, где он читается.
 *
 * Переменная **серверная** (`GA_ID`, а не `NEXT_PUBLIC_GA_ID`), и это решение.
 * `NEXT_PUBLIC_*` подставляется сборкой, то есть переменная становится частью
 * бандла: сменить счётчик или выключить его на Vercel без пересборки было бы
 * нельзя, а тестовый сервер получил бы значение только от `npm run build`, а не
 * от своего окружения. Серверную же читает сам сервер и при каждом запросе.
 *
 * В браузер идентификатор уезжает пропом — тем же путём, каким туда попадает
 * всё остальное серверное в этом проекте.
 */
export function analyticsId(): string | null {
  return process.env.GA_ID || null
}
