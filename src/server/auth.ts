import NextAuth from 'next-auth'
import Google from 'next-auth/providers/google'

/**
 * Вход в сайт. Хранилища у него нет намеренно: адаптер БД не подключён, поэтому
 * Auth.js держит сессию в зашифрованной куке (стратегия JWT), а на сервере не
 * остаётся ни строчки о пользователе. Серверная копия появится вместе с Postgres
 * и кнопкой «Сохранить» — тогда адаптер добавится рядом, а не вместо этого.
 *
 * Провайдер пока один. Второй — это строка в `providers` и кнопка в
 * `LoginButtons`, больше нигде о нём знать не нужно.
 *
 * Ключи Google читаются из `AUTH_GOOGLE_ID` и `AUTH_GOOGLE_SECRET` сами: Auth.js
 * ищет переменные по имени провайдера, поэтому в конфиге их нет. Набор данных —
 * умолчание Google-провайдера (`openid email profile`), и переопределять его
 * незачем: имя с почтой всё равно никуда дальше куки не уезжают.
 */
export const { handlers, auth, signIn, signOut } = NextAuth({
  providers: [Google],
})
