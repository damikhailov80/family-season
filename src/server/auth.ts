import NextAuth from 'next-auth'
import Google from 'next-auth/providers/google'

/**
 * Вход в сайт. Хранилища у него нет намеренно: адаптер БД не подключён, поэтому
 * Auth.js держит сессию в зашифрованной куке (стратегия JWT), а на сервере не
 * остаётся ни строчки о пользователе. Серверная копия появится вместе с Postgres
 * и кнопкой «Сохранить» — тогда адаптер добавится рядом, а не вместо этого.
 *
 * Провайдер пока один. Второй — это строка в `providers` и кнопка в
 * `LoginButtons`, больше нигде о нём знать не нужно.
 *
 * Ключи Google читаются из `AUTH_GOOGLE_ID` и `AUTH_GOOGLE_SECRET` сами: Auth.js
 * ищет переменные по имени провайдера, поэтому в конфиге их нет. Набор данных —
 * умолчание Google-провайдера (`openid email profile`), и переопределять его
 * незачем: имя с почтой всё равно никуда дальше куки не уезжают.
 */
export const { handlers, auth, signIn, signOut } = NextAuth({
  providers: [Google],
  callbacks: {
    /*
     * Единственное, что мы кладём в сессию сверх умолчаний, — постоянный ключ
     * аккаунта. Он нужен настройкам (`src/server/settings.ts`) как имя строки
     * в базе.
     *
     * Именно провайдер плюс его идентификатор, а не почта: почту меняют, и
     * настройки бы потерялись, а сам ключ ничего о человеке не сообщает —
     * по нему нельзя узнать ни имени, ни адреса. `account` приходит только в
     * тот заход, когда человек вошёл, поэтому дальше ключ просто едет в токене.
     */
    jwt({ token, account }) {
      if (account) token.accountKey = `${account.provider}:${account.providerAccountId}`
      return token
    },
    session({ session, token }) {
      /*
       * Ключа может не быть — у сессий, выпущенных до появления этого колбэка.
       * Подставлять вместо него `token.sub` **нельзя**, хотя соблазн есть:
       * без адаптера БД Auth.js кладёт туда случайный UUID, который живёт лишь
       * до конца сессии. Настройки по такому ключу нашлись бы сегодня и
       * потерялись при следующем входе. Пусть лучше ключа не будет вовсе —
       * кабинет это увидит и попросит войти заново.
       */
      session.accountKey = token.accountKey
      return session
    },
  },
})
