/**
 * Подстановка в строку словаря: `fill('Больше {n} нельзя', { n: 100 })`.
 *
 * Значения словаря — **строки, а не функции**, и это не стилистика: словарь
 * едет в клиентские компоненты внутри RSC-нагрузки, а функции не сериализуются.
 * Отсюда и пометки в фигурных скобках, и этот хелпер.
 *
 * Пропущенный ключ оставляем как есть, а не подставляем пустоту: дырка в
 * интерфейсе заметна, а «Больше  сезонов» читается как опечатка и живёт годами.
 */
export function fill(text: string, vars: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (whole, key) => (key in vars ? String(vars[key]) : whole))
}

/**
 * Разбор `**жирного**` в строке словаря.
 *
 * Нужен ровно одной странице — политике приватности: там смысл держится на
 * выделенных словах («**копия**», «**только в вашем браузере**»), и разрезать
 * их на отдельные ключи значило бы отдать перевод по кускам, из которых фразу
 * уже не собрать. Разметки богаче этой в текстах нет и заводить её не надо.
 *
 * Возвращает куски по порядку; `bold` — надо ли обернуть кусок в `<b>`.
 */
export function marked(text: string): { text: string; bold: boolean }[] {
  return text
    .split(/\*\*/)
    .map((piece, index) => ({ text: piece, bold: index % 2 === 1 }))
    .filter((piece) => piece.text !== '')
}
