import type { ru } from './dict/ru'

/**
 * Форма словаря выводится из русского: он эталон, потому что с него сайт
 * начинался и в нём заводятся новые строки. `en.ts` и `pl.ts` объявлены как
 * `const en: Dict`, поэтому забытый ключ — ошибка `npm run typecheck`, а не
 * дырка в интерфейсе, которую заметит первый же читатель.
 *
 * `as const` на словаре намеренно **нет**: он сузил бы значения до самих
 * русских строк, и перевод перестал бы им соответствовать.
 */
export type Dict = typeof ru
