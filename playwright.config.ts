import { defineConfig, devices } from '@playwright/test'

/**
 * E2E гоняются **локально, перед push** (`.husky/pre-push`), а не шагом сборки
 * на Vercel. Причина не в Playwright, а в правиле проекта: билд обязан
 * оставаться тем, что просто собирает сайт, и падение тестовой базы не имеет
 * права мешать деплою сайта, который работает и с мёртвой базой.
 *
 * Перед прогоном базу приводит к слепку `npm run e2e:db`.
 */

/*
 * `AUTH_SECRET` нужен самим тестам — им подделывается кука сессии
 * (`e2e/support/session.ts`), — а `E2E_DATABASE_URL` уезжает серверу под тестом.
 * Playwright `.env.local` сам не читает, а тащить ради двух строк `dotenv` незачем.
 */
try {
  process.loadEnvFile('.env.local')
} catch {
  // Файла может не быть (CI, чужая машина) — тогда переменные приходят снаружи.
}

/**
 * Тесты живут на своём порту, а не на 3000.
 *
 * Это не вкусовщина, а единственный способ не сжечь дев-базу: дев-сервер
 * разработчика обычно уже поднят на 3000 и смотрит в рабочую базу, а
 * `reuseExistingServer` подхватил бы именно его — вместе с его `DATABASE_URL`,
 * потому что подмена окружения касается только сервера, который Playwright
 * запускает сам. На 3100 же ничего, кроме тестового сервера, не бывает.
 */
const PORT = 3100
const baseURL = `http://localhost:${PORT}`

export default defineConfig({
  testDir: 'e2e',
  fullyParallel: true,

  /*
   * Слепок накатывается один раз на прогон, а тесты идут параллельно — изоляция
   * держится на том, что каждому тесту выдан свой `accountKey` (см. фикстуру
   * `signedIn`). Общее у них только то, что и так общее у всех: витрина.
   */
  workers: process.env.CI ? 2 : undefined,
  retries: process.env.CI ? 2 : 0,
  reporter: process.env.CI ? 'list' : [['list'], ['html', { open: 'never' }]],

  use: { baseURL, trace: 'retain-on-failure' },

  projects: [{ name: 'chromium', use: devices['Desktop Chrome'] }],

  /*
   * Собранный сервер, а не дев. Дев тут невозможен в принципе: `next dev`
   * держит замок в `distDir` и второй сервер в том же проекте не поднимет —
   * а первый, разработчика, смотрит в рабочую базу. Сборка при этом дешёвая
   * (около десяти секунд на тёплом кэше) и вдобавок проверяет ровно то, что
   * уезжает в прод.
   *
   * Собирает `npm run e2e:all`; здесь только запуск, чтобы отдельный
   * `playwright test` не пересобирал проект на каждый прогон.
   *
   * `DATABASE_URL` подменяется тестовой базой прямо здесь: так приложение под
   * тестом смотрит куда надо, а `src/server/db.ts` остаётся нетронутым — он как
   * читал `DATABASE_URL`, так и читает.
   */
  webServer: {
    command: `npm run start -- --port ${PORT}`,
    url: baseURL,
    reuseExistingServer: true,
    timeout: 120_000,
    env: {
      DATABASE_URL: process.env.E2E_DATABASE_URL ?? '',
      /*
       * Auth.js в прод-режиме отказывается доверять хосту, если тот не назван
       * явно: `UntrustedHost`, и сессия не читается вовсе. На Vercel хост
       * подставляется сам, локально — некому. Это настройка тестового сервера,
       * а не кода: `src/server/auth.ts` о ней не знает.
       */
      AUTH_TRUST_HOST: 'true',
      AUTH_URL: baseURL,
      /*
       * Без идентификатора счётчика согласия не спрашивают вовсе — ни баннера,
       * ни ссылки в подвале, ни раздела в кабинете (см. `analyticsId`). Значит,
       * тестировать было бы нечего. Идентификатор заведомо ненастоящий, а сам
       * запрос к Google тесты глушат `page.route`.
       *
       * Работает это только потому, что переменная серверная: `NEXT_PUBLIC_*`
       * подставляется сборкой, и здесь, в окружении уже собранного сервера,
       * она бы ничего не изменила.
       */
      GA_ID: 'G-E2ETEST',
    },
  },
})
