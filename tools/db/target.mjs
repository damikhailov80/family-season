/**
 * Куда именно едем — без пользователя и пароля.
 *
 * Печатается перед подключением каждым скриптом, который трогает базу, и это не
 * украшение: прод накатывают руками, `--env-file` подставляют руками же, и
 * единственная защита от «сел не в тот поезд» — увидеть хост до того, как что-то
 * записалось.
 */
export function dbTarget(value) {
  try {
    const parsed = new URL(value)
    return `${parsed.hostname}${parsed.port ? `:${parsed.port}` : ''}${parsed.pathname}`
  } catch {
    return 'адрес не разобрался'
  }
}
