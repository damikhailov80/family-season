-- Языки: русский, английский, польский.
--
-- Язык живёт в двух разных смыслах, и колонок поэтому две породы.
--
-- `user_settings.language` — **настройка человека**: им подписан интерфейс.
-- Меняется в кабинете, стоит в адресе, дублируется кукой браузера. Заведённых
-- сезонов не трогает — ровно как не трогает их состав семьи.
--
-- `user_seasons.language` и `public_seasons.language` — **язык сезона**: им
-- подписан сам лист (месяц, подписи секций, подсказки пустых полей). Он
-- печатается, поэтому переключение сайта не имеет права его переписать:
-- русский сезон остаётся русским, даже когда его открыли из английской
-- витрины. Ставится при заведении строки, копируется при публикации и там
-- может быть выбран руками — в окне публикации есть список языков.
--
-- Внутрь `content` язык не идёт намеренно. Он лежит колонкой рядом, как тема и
-- набор рисунков: в бланк они не входят, а печатаются. Иначе пришлось бы
-- поднимать версию формата (`codec.ts`) и переписывать все строки в базе ради
-- значения, которое к самому бланку отношения не имеет.
--
-- `default 'ru'` — не заглушка, а правда: всё, что лежало в базе до этого шага,
-- собрано на русском.

alter table user_settings  add column if not exists language text not null default 'ru';
alter table user_seasons   add column if not exists language text not null default 'ru';
alter table public_seasons add column if not exists language text not null default 'ru';

-- Уникальность публикации считается **вместе с языком**. Тот же бланк,
-- переведённый на другой язык, — другая идея: на витрине их видят разные люди,
-- и отбивать второй как дубль первого значило бы запереть витрину за тем, кто
-- успел первым. Ключ по-прежнему считает база, а не приложение: иначе он
-- зависел бы от того, кто и чем его посчитал.
--
-- Колонка генерируемая, поэтому выражение меняется только пересозданием.
alter table public_seasons drop column if exists content_key;
alter table public_seasons add column content_key text
  generated always as (md5(language || content::text)) stored;
create unique index if not exists public_seasons_content on public_seasons (content_key);

-- Витрина спрашивает свой язык у каждой выборки. Индекс частичный по тому же
-- условию, что и сама выборка: снятое и закрытое на витрине не показывается.
create index if not exists public_seasons_lang
  on public_seasons (language) where hidden_at is null and blocked_at is null;

-- Жалоба носит снимок публикации, а не ссылку на неё (см. `004`), — значит,
-- язык нужен и снимку: разбирают жалобу по тексту, а у пустого поля бланка
-- текст берётся из подсказки, и подсказка эта своя у каждого языка. Без колонки
-- очередь разбора показывала бы польский сезон с русской подписью.
alter table public_reports add column if not exists language text not null default 'ru';
