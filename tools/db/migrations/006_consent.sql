-- Согласие на аналитику.
--
-- До этого шага всё, что сайт собирал, собиралось **ради самого человека**: без
-- состава семьи не собрать бланк, без строки сезона нечего показать. Такой
-- обработке согласие не нужно — она и есть услуга, за которой пришли. Google
-- Analytics — первый случай, когда данные собираются ради нас, а не ради него,
-- и вот он согласия требует: своего, отзывного и данного **до** первой куки.
--
-- Колонок три, и каждая отвечает на свой вопрос разбора.
--
-- `consent` — что ответили: `granted` или `denied`. `null` здесь значит **«не
-- спрашивали»**, а не «запрещено», и разница та же, что у `language`: по `null`
-- сайт понимает, что баннер ещё не показывали. Умолчания у колонки поэтому нет
-- и быть не может — умолчание означало бы, что за человека уже ответили.
--
-- `consent_version` — на что именно согласились. Согласие даётся на конкретный
-- набор целей: станет целей больше — прежний ответ перестанет что-либо значить,
-- и спросить придётся заново. Версия живёт числом в `src/model/consent.ts`;
-- записанная версия меньше текущей читается как «не спрашивали».
--
-- `consent_at` — когда. Это то самое доказательство согласия, которое GDPR
-- требует уметь предъявить; без даты запись отвечает «да», но не отвечает
-- «когда», а через год разница как раз и понадобится.
--
-- Своей таблицы согласию не заводим. «Создание пользователя» у нас — первая
-- строка `user_settings`: таблицы людей нет, есть непрозрачный ключ из сессии.
-- История согласий отдельной таблицей была бы полнее для аудита, но версия у
-- нас пока одна, и таблица хранила бы по одной строке на человека — то есть ту
-- же колонку, только дороже.
--
-- Настоящее хранилище ответа — кука `fs-consent`: решение принимают в браузере,
-- и невошедшему больше негде его держать. Колонки нужны затем, чтобы вошедший
-- не отвечал на один и тот же вопрос на каждом своём устройстве, и затем, чтобы
-- решение можно было пересмотреть в кабинете.

alter table user_settings add column if not exists consent         text;
alter table user_settings add column if not exists consent_version int;
alter table user_settings add column if not exists consent_at      timestamptz;
